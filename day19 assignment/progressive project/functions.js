function js(a,b,c){
    if(c==1){
        console.log(a+b);
    }
    else if(c==2){
        console.log(a*b);
    }
    else if(c==3){
        console.log(a-b);
    }
    else if(c==4){
        console.log(a/b);
    }
    else if(c==5){
        console.log(a%b);
    }
    else{
        console.log("error");
    }
}
js(2,4,5);